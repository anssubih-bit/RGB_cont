import Foundation

/// Command frames for ELK-BLEDOM / LEDBLE / LotusLanternX controllers.
/// Every frame is 9 bytes: 0x7E ... 0xEF, written to characteristic FFF3 (service FFF0).
enum LED {
    static func powerOn(alt: Bool = false) -> Data {
        Data(alt ? [0x7e,0x04,0x04,0x01,0x00,0x00,0x00,0x00,0xef] : [0x7e,0x00,0x04,0xf0,0x00,0x01,0xff,0x00,0xef])
    }
    static func powerOff(alt: Bool = false) -> Data {
        Data(alt ? [0x7e,0x04,0x04,0x00,0x00,0x00,0x00,0x00,0xef] : [0x7e,0x00,0x04,0x00,0x00,0x00,0xff,0x00,0xef])
    }
    static func color(r: UInt8, g: UInt8, b: UInt8) -> Data { Data([0x7e,0x00,0x05,0x03,r,g,b,0x00,0xef]) }
    /// 0...100
    static func brightness(_ v: UInt8) -> Data { Data([0x7e,0x00,0x01,min(v,100),0x00,0x00,0x00,0x00,0xef]) }
    static func effect(_ code: UInt8) -> Data { Data([0x7e,0x00,0x03,code,0x03,0x00,0x00,0x00,0xef]) }
    /// 0...100
    static func speed(_ v: UInt8) -> Data { Data([0x7e,0x00,0x02,min(v,100),0x00,0x00,0x00,0x00,0xef]) }

    static let effects: [(name: String, code: UInt8)] = [
        ("Jump RGB",0x87),("Jump 7 colors",0x88),("Fade RGB",0x89),("Fade 7 colors",0x8a),
        ("Breathe red",0x8b),("Breathe green",0x8c),("Breathe blue",0x8d),("Breathe yellow",0x8e),
        ("Breathe cyan",0x8f),("Breathe purple",0x90),("Breathe white",0x91),("Fade red/green",0x92),
        ("Fade red/blue",0x93),("Fade green/blue",0x94),("Strobe 7 colors",0x95),("Strobe red",0x96),
        ("Strobe green",0x97),("Strobe blue",0x98),("Strobe yellow",0x99),("Strobe cyan",0x9a),
        ("Strobe purple",0x9b),("Strobe white",0x9c),
    ]
}
